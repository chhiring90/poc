import type { Metadata } from "next";
import { getSiteSettings } from "@/lib/seo/get-site-settings";
import {
  parseMedia,
  parseSeo,
  toPlainText,
  truncate,
  type SeoMedia,
} from "@/lib/seo/parse";

export type PageSeoInput = {
  /** Path of the page, e.g. "/services/web-design". Becomes the canonical URL. */
  path: string;
  /** The `seo` group from the CMS document (optional overrides). */
  seo?: unknown;
  /** Fallbacks taken from the page's own content. */
  title?: string | null;
  description?: string | null;
  image?: unknown;
  /** Home page: use the title as-is, without the "| Site name" suffix. */
  isHome?: boolean;
  /** Extra reason to keep the page out of search, e.g. an unpublished draft. */
  noIndex?: boolean;
  article?: {
    publishedTime?: string | null;
    modifiedTime?: string | null;
    authors?: string[];
    section?: string | null;
    tags?: string[];
  };
};

function toImages(media: SeoMedia | null, title: string) {
  if (media) {
    return [
      {
        url: media.url,
        alt: media.alt ?? title,
        ...(media.width ? { width: media.width } : {}),
        ...(media.height ? { height: media.height } : {}),
      },
    ];
  }

  // No image anywhere: use the branded image generated by app/og/route.tsx.
  return [
    {
      url: `/og?title=${encodeURIComponent(title)}`,
      alt: title,
      width: 1200,
      height: 630,
    },
  ];
}

/**
 * Builds page metadata from CMS SEO overrides, then page content, then site defaults.
 * Every public page should use this so titles, canonicals and share cards stay consistent.
 */
export async function buildPageMetadata(input: PageSeoInput): Promise<Metadata> {
  const settings = await getSiteSettings();
  const seo = parseSeo(input.seo);

  const pageTitle = seo.title ?? toPlainText(input.title);
  const homeTitle = pageTitle ?? settings.defaultTitle ?? settings.siteName;
  const fullTitle = input.isHome
    ? homeTitle
    : pageTitle
      ? `${pageTitle} | ${settings.siteName}`
      : settings.siteName;
  const description = truncate(
    seo.description ??
      toPlainText(input.description) ??
      settings.defaultDescription,
  );
  const images = toImages(
    seo.image ?? parseMedia(input.image) ?? settings.defaultImage,
    pageTitle ?? homeTitle,
  );
  const noIndex = seo.noIndex || input.noIndex;
  const article = input.article;

  return {
    // Keys are left out (not set to undefined) so the layout defaults still apply.
    ...(input.isHome
      ? { title: { absolute: homeTitle } }
      : pageTitle
        ? { title: pageTitle }
        : {}),
    ...(description ? { description } : {}),
    alternates: { canonical: input.path },
    ...(noIndex ? { robots: { index: false, follow: true } } : {}),
    openGraph: {
      siteName: settings.siteName,
      locale: settings.locale,
      url: input.path,
      title: fullTitle,
      description: description ?? undefined,
      images,
      ...(article
        ? {
            type: "article" as const,
            publishedTime: article.publishedTime ?? undefined,
            modifiedTime: article.modifiedTime ?? undefined,
            authors: article.authors,
            section: article.section ?? undefined,
            tags: article.tags,
          }
        : { type: "website" as const }),
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description: description ?? undefined,
      images: images.map(({ url, alt }) => ({ url, alt })),
      ...(settings.twitterHandle
        ? { site: settings.twitterHandle, creator: settings.twitterHandle }
        : {}),
    },
  };
}
